CREATE TABLE IF NOT EXISTS achievements (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    slug VARCHAR(191) NOT NULL UNIQUE,
    name VARCHAR(191) NOT NULL,
    description TEXT NULL,
    category_id BIGINT UNSIGNED NULL,
    rarity VARCHAR(50) NULL COMMENT 'Vocabulaire métier à confirmer ; NULL = inconnue',
    secret_type ENUM('unknown', 'normal', 'secret') NOT NULL DEFAULT 'unknown',
    reward_xp BIGINT UNSIGNED NULL COMMENT 'NULL = inconnu ; 0 = aucune récompense',
    reward_gold BIGINT UNSIGNED NULL,
    reward_gems BIGINT UNSIGNED NULL,
    reward_keys BIGINT UNSIGNED NULL,
    title_rewards_known BOOLEAN NOT NULL DEFAULT FALSE,
    verification_status ENUM('unverified', 'pending', 'verified', 'rejected') NOT NULL DEFAULT 'unverified',
    source_url VARCHAR(2048) NULL,
    created_by BIGINT UNSIGNED NULL,
    verified_by BIGINT UNSIGNED NULL,
    verified_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_achievement_category FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE SET NULL,
    CONSTRAINT fk_achievement_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_achievement_verifier FOREIGN KEY (verified_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_title_rewards_known CHECK (title_rewards_known IN (0, 1)),
    CONSTRAINT chk_verification_date CHECK ((verification_status = 'verified' AND verified_at IS NOT NULL)
        OR (verification_status <> 'verified' AND verified_at IS NULL)),
    INDEX idx_achievement_category (category_id),
    INDEX idx_achievement_rarity (rarity),
    INDEX idx_achievement_secret (secret_type),
    INDEX idx_achievement_verification (verification_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
